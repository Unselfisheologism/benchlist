/**
 * Get catalog entries filtered by various criteria
 */
export function searchCatalog(query?: string, category?: string, org?: string): BenchmarkSource[] {
  let results = BENCHMARK_CATALOG

  if (category) {
    results = results.filter((b) => b.category === category)
  }

  if (org) {
    const lowerOrg = org.toLowerCase()
    results = results.filter(
      (b) =>
        b.org?.toLowerCase().includes(lowerOrg) || b.source_type.toLowerCase().includes(lowerOrg),
    )
  }

  if (query) {
    const lower = query.toLowerCase()
    results = results.filter(
      (b) =>
        b.name.toLowerCase().includes(lower) ||
        b.description.toLowerCase().includes(lower) ||
        b.tags?.some((t) => t.toLowerCase().includes(lower)) ||
        b.org?.toLowerCase().includes(lower) ||
        b.category.toLowerCase().includes(lower),
    )
  }

  return results
}
